"""
backend/report_generator.py
============================
PDF report generator for AquaVeda using fpdf2.
All chart images are generated with matplotlib (no kaleido/plotly export).

Usage
-----
    from backend.report_generator import generate_watershed_report

    pdf_bytes = generate_watershed_report(
        watershed_info=ws_dict,
        change_data=change_dict,
        health_score=health_dict,
        timeseries_data=ts_dict,
        photos_data=photos_list,
    )
    # Pass pdf_bytes to st.download_button(mime="application/pdf")
"""

import os
import datetime
import tempfile

from fpdf import FPDF
from frontend.charts_matplotlib import save_all_report_charts


# ─── brand colours (RGB) ──────────────────────────────────────────────────────
_BLUE       = (30,  136, 229)   # header / accent
_DARK       = (15,   23,  42)   # cover background
_WHITE      = (255, 255, 255)
_LIGHT_GRAY = (241, 245, 249)
_MID_GRAY   = (148, 163, 184)
_TEXT       = (30,   41,  59)
_GREEN      = (26,  152,  80)
_ORANGE     = (245, 110,  67)
_RED        = (215,  48,  39)


# ─── helper: grade -> colour ───────────────────────────────────────────────────
def _grade_color(score: int) -> tuple:
    if score >= 80: return _GREEN
    if score >= 60: return (253, 196,  0)
    if score >= 40: return _ORANGE
    return _RED


# ─── Custom FPDF subclass ─────────────────────────────────────────────────────
class _AquaVedaPDF(FPDF):
    """FPDF2 subclass with branded header/footer and helpers."""

    def __init__(self, watershed_name: str = ""):
        super().__init__(orientation="P", unit="mm", format="A4")
        self._ws_name = watershed_name
        self.set_margins(left=14, top=14, right=14)
        self.set_auto_page_break(auto=True, margin=18)

    # ── Automatic header ──────────────────────────────────────────────────────
    def header(self):
        if self.page_no() == 1:
            return  # Cover page has its own design

        # Blue rule at top
        self.set_fill_color(*_BLUE)
        self.rect(0, 0, 210, 8, "F")

        self.set_y(10)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*_MID_GRAY)
        self.cell(0, 5, f"AquaVeda  |  Watershed Impact Report  |  {self._ws_name}", ln=False, align="L")
        self.cell(0, 5, f"Page {self.page_no()}", ln=True, align="R")
        self.ln(3)

    # ── Text sanitization ─────────────────────────────────────────────────────
    def normalize_text(self, text):
        """Sanitize text to latin-1 to prevent fpdf2 crashes on dynamic data."""
        if not isinstance(text, str):
            text = str(text)
        repl = {
            '\u2013': '-', '\u2014': '-', '\u2018': "'", '\u2019': "'",
            '\u201c': '"', '\u201d': '"', '\u2022': '*', '\u2026': '...',
            '\u2192': '->', '\U0001F30A': '~~ AquaVeda ~~'
        }
        for k, v in repl.items():
            text = text.replace(k, v)
        # Fallback for any other non-latin-1 char (replaced with '?')
        text = text.encode("latin-1", "replace").decode("latin-1")
        return super().normalize_text(text)

    # ── Automatic footer ──────────────────────────────────────────────────────
    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-12)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(*_MID_GRAY)
        self.cell(0, 5,
            "Generated by AquaVeda - Satellite-Based Watershed Monitor  |  SIH 2026",
            align="C")

    # ── Helpers ───────────────────────────────────────────────────────────────
    def section_title(self, text: str):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(*_BLUE)
        self.cell(0, 10, text, ln=True)
        self.set_draw_color(*_BLUE)
        self.set_line_width(0.5)
        self.line(14, self.get_y(), 196, self.get_y())
        self.set_draw_color(0, 0, 0)
        self.set_line_width(0.2)
        self.set_text_color(*_TEXT)
        self.ln(4)

    def kv_row(self, key: str, value: str, highlight: bool = False):
        """Single key-value line with optional colour highlight."""
        if highlight:
            self.set_fill_color(*_LIGHT_GRAY)
            self.set_font("Helvetica", "B", 11)
            self.cell(0, 8, f"  {key}: {value}", fill=True, ln=True)
            self.set_font("Helvetica", "", 11)
        else:
            self.set_font("Helvetica", "", 11)
            self.cell(0, 7, f"  *  {key}: {value}", ln=True)

    def bullet(self, text: str, indent: int = 6):
        self.set_font("Helvetica", "", 11)
        self.set_x(14 + indent)
        self.multi_cell(0, 7, f"*  {text}")

    def table_header(self, cols: list, widths: list):
        self.set_fill_color(*_BLUE)
        self.set_text_color(*_WHITE)
        self.set_font("Helvetica", "B", 10)
        for col, w in zip(cols, widths):
            self.cell(w, 8, col, border=1, fill=True, align="C")
        self.ln()
        self.set_text_color(*_TEXT)

    def table_row(self, values: list, widths: list, shade: bool = False):
        if shade:
            self.set_fill_color(*_LIGHT_GRAY)
        else:
            self.set_fill_color(*_WHITE)
        self.set_font("Helvetica", "", 10)
        for val, w in zip(values, widths):
            self.cell(w, 7, str(val), border=1, fill=True, align="C")
        self.ln()

    def safe_image(self, path, x=None, w=None, h=0):
        """Add image only if path exists and file is non-empty."""
        if path and os.path.exists(path) and os.path.getsize(path) > 0:
            try:
                self.image(path, x=x, w=w, h=h)
                return True
            except Exception as e:
                print(f"[WARN] PDF image insert failed ({path}): {e}")
        return False


